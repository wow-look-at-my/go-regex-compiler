// countGroups counts capture groups in a parsed regex.
func countGroups(re *syntax.Regexp) int {
	n := 0
	if re.Op == syntax.OpCapture {
		n = 1
	}
	for _, sub := range re.Sub {
		n += countGroups(sub)
	}
	return n
}

